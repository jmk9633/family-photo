/** 이름 뒤 '이/가': 마지막 글자에 받침이 있으면 '이' (지은이, 엄마가). 한글이 아니면 '가'. */
function iga(name: string): string {
  const c = name.trim().charCodeAt(name.trim().length - 1);
  const hasFinal = c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 !== 0;
  return `${name}${hasFinal ? '이' : '가'}`;
}

